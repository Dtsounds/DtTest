// ── ITEMS ──────────────────────────────────────────────────────────────────

function generateItemBP(item, namespace) {
  const id = resolveId(item.identifier, namespace);

  const categoryMap = {
    Items: 'items', Nature: 'nature',
    Equipment: 'equipment', Construction: 'construction', Command: 'none'
  };

  const texName = id.replace(':', '_');

  const components = {
    'minecraft:max_stack_size': Math.min(64, Math.max(1, parseInt(item.maxStackSize) || 1)),
    'minecraft:icon': { texture: texName }
  };

  if (item.isWeapon) {
    if (parseInt(item.damage) > 0) {
      components['minecraft:damage'] = parseInt(item.damage);
    }
    if (parseInt(item.durability) > 0) {
      components['minecraft:durability'] = { max_durability: parseInt(item.durability) };
    }
  }

  if (item.isFood) {
    const food = {
      nutrition: parseInt(item.nutrition) || 4,
      saturation_modifier: item.saturationModifier || 'normal'
    };
    if (item.canAlwaysEat) food.can_always_eat = true;
    components['minecraft:food'] = food;
  }

  if (item.isFoil || item.isGlint) {
    components['minecraft:glint'] = true;
  }

  if (item.isThrowable) {
    components['minecraft:throwable'] = { do_swing_animation: true, launch_power_scale: 1.0, max_launch_power: 1.0 };
    components['minecraft:projectile'] = { projectile_entity: 'minecraft:snowball', minimum_critical_power: 1.0 };
  }

  if (item.handEquipped) {
    components['minecraft:hand_equipped'] = true;
  }

  return {
    format_version: '1.20.10',
    'minecraft:item': {
      description: {
        identifier: id,
        menu_category: { category: categoryMap[item.category] || 'items' }
      },
      components
    }
  };
}

// ── BLOCKS ─────────────────────────────────────────────────────────────────

function generateBlockBP(block, namespace) {
  const id = resolveId(block.identifier, namespace);
  const textureName = id.replace(':', '_');

  const categoryMap = {
    Construction: 'construction', Nature: 'nature',
    Items: 'items', Equipment: 'equipment'
  };

  const components = {};

  const hardness = parseFloat(block.hardness);
  if (hardness >= 0) {
    components['minecraft:destructible_by_mining'] = { seconds_to_destroy: hardness };
  } else {
    // Indestructible
    components['minecraft:destructible_by_mining'] = false;
  }

  components['minecraft:destructible_by_explosion'] = {
    explosion_resistance: parseFloat(block.resistance) || 6.0
  };

  components['minecraft:friction'] = parseFloat(block.friction) || 0.6;

  if (block.isFlammable) {
    components['minecraft:flammable'] = {
      catch_chance_modifier: parseInt(block.flamOdds) || 5,
      destroy_chance_modifier: parseInt(block.burnOdds) || 20
    };
  }

  if (block.mapColor) {
    components['minecraft:map_color'] = block.mapColor;
  }

  const lightEmission = parseInt(block.lightEmission) || 0;
  if (lightEmission > 0) {
    components['minecraft:light_emission'] = lightEmission;
  }

  const lightDampening = parseInt(block.lightDampening);
  if (!isNaN(lightDampening)) {
    components['minecraft:light_dampening'] = lightDampening;
  }

  components['minecraft:geometry'] = 'minecraft:geometry.full_block';

  components['minecraft:material_instances'] = {
    '*': {
      texture: textureName,
      render_method: block.isTransparent ? 'blend' : 'opaque'
    }
  };

  return {
    format_version: '1.20.10',
    'minecraft:block': {
      description: {
        identifier: id,
        menu_category: { category: categoryMap[block.category] || 'construction' }
      },
      components
    }
  };
}

// ── ENTITIES ───────────────────────────────────────────────────────────────

function generateEntityBP(entity, namespace) {
  const id = resolveId(entity.identifier, namespace);

  const components = {
    'minecraft:type_family': {
      family: entity.isHostile ? ['monster', 'mob'] : ['mob', 'animal']
    },
    'minecraft:health': {
      value: parseInt(entity.health) || 20,
      max: parseInt(entity.health) || 20
    },
    'minecraft:movement': {
      value: parseFloat(entity.movementSpeed) || 0.25
    },
    'minecraft:collision_box': {
      width: parseFloat(entity.collisionWidth) || 0.6,
      height: parseFloat(entity.collisionHeight) || 1.8
    },
    'minecraft:navigation.walk': {
      can_path_over_water: true,
      avoid_water: !entity.swimsInWater
    },
    'minecraft:movement.basic': {},
    'minecraft:jump.static': {},
    'minecraft:breathable': {
      breathes_air: true,
      breathes_water: !!entity.swimsInWater,
      total_supply: 15,
      suffocate_time: -1
    },
    'minecraft:physics': {},
    'minecraft:behavior.look_at_player': { priority: 7, look_distance: 8 },
    'minecraft:behavior.random_look_around': { priority: 8 },
    'minecraft:behavior.random_stroll': { priority: 6, speed_multiplier: 1.0 }
  };

  if (entity.isHostile) {
    components['minecraft:attack'] = { damage: parseInt(entity.attackDamage) || 3 };
    components['minecraft:behavior.melee_attack'] = { priority: 3 };
    components['minecraft:behavior.nearest_attackable_target'] = {
      priority: 2,
      entity_types: [{
        filters: { test: 'is_family', subject: 'other', value: 'player' }
      }]
    };
  }

  if (entity.isTameable) {
    components['minecraft:tameable'] = {
      probability: 0.33,
      tame_items: ['minecraft:bone'],
      tame_event: { event: 'minecraft:on_tame', target: 'self' }
    };
    components['minecraft:behavior.follow_owner'] = {
      priority: 4,
      speed_multiplier: 1.0,
      start_distance: 10.0,
      stop_distance: 2.0
    };
  }

  if (entity.swimsInWater) {
    components['minecraft:underwater_movement'] = { value: parseFloat(entity.movementSpeed) * 0.5 || 0.12 };
    components['minecraft:navigation.swim'] = { can_path_over_water: true };
  }

  if (parseInt(entity.dropsXP) > 0) {
    components['minecraft:experience_reward'] = {
      on_death: `query.last_hit_by_player ? ${entity.dropsXP} : 0`
    };
  }

  if (parseFloat(entity.knockbackResist) > 0) {
    components['minecraft:knockback_resistance'] = {
      value: parseFloat(entity.knockbackResist)
    };
  }

  return {
    format_version: '1.20.10',
    'minecraft:entity': {
      description: {
        identifier: id,
        is_spawnable: entity.isSpawnable !== false,
        is_summonable: true,
        is_experimental: false
      },
      component_groups: {},
      components,
      events: {}
    }
  };
}

