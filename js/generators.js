function generateTerrainTexture(blocks, namespace, packName) {
  const texture_data = {};
  for (const block of blocks) {
    const id = resolveId(block.identifier, namespace);
    const texName = id.replace(':', '_');
    texture_data[texName] = { textures: `textures/blocks/${texName}` };
  }
  return {
    resource_pack_name: packName || 'vanilla',
    texture_name: 'atlas.terrain',
    padding: 8,
    num_mip_levels: 4,
    texture_data
  };
}

function generateItemTexture(items, namespace, packName) {
  const texture_data = {};
  for (const item of items) {
    const id = resolveId(item.identifier, namespace);
    const texName = id.replace(':', '_');
    texture_data[texName] = { textures: `textures/items/${texName}` };
  }
  return {
    resource_pack_name: packName || 'vanilla',
    texture_name: 'atlas.items',
    texture_data
  };
}

function generateLangFile(items, blocks, entities, namespace) {
  const lines = [];
  for (const item of items) {
    const id = resolveId(item.identifier, namespace);
    const name = item.displayName || id.split(':').pop();
    lines.push(`item.${id}.name=${name}`);
  }
  for (const block of blocks) {
    const id = resolveId(block.identifier, namespace);
    const name = block.displayName || id.split(':').pop();
    lines.push(`tile.${id}.name=${name}`);
  }
  for (const entity of entities) {
    const id = resolveId(entity.identifier, namespace);
    const name = entity.displayName || id.split(':').pop();
    lines.push(`entity.${id}.name=${name}`);
  }
  return lines.join('\n');
}

// ── SYNTAX HIGHLIGHTING ────────────────────────────────────────────────────

function syntaxHighlight(json) {
  if (typeof json !== 'string') {
    json = JSON.stringify(json, null, 2);
  }
  return json
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(
      /("(\\u[a-zA-Z0-9]{4}|\\[^u]|[^\\"])*"(\s*:)?|\b(true|false|null)\b|-?\d+(?:\.\d*)?(?:[eE][+\-]?\d+)?)/g,
      match => {
        let cls = 'json-num';
        if (/^"/.test(match)) {
          cls = /:$/.test(match) ? 'json-key' : 'json-str';
        } else if (/true|false/.test(match)) {
          cls = 'json-bool';
        } else if (/null/.test(match)) {
          cls = 'json-null';
        }
        return `<span class="${cls}">${match}</span>`;
      }
    );
}
